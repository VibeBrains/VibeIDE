/**
 * Есть ли на странице PDF текстовый слой — и что делать, когда его нет.
 *
 * WHY: PDF бывает двух пород. У обычного внутри лежит текст, и мы его читаем. У сканированного
 * внутри картинка, а текста нет вовсе — и до 19.09.2026 такая страница приезжала в контекст пустой
 * строкой. Молча: модель видела «страница 3» без единого слова и делала вид, что прочитала.
 *
 * Порог намеренно низкий. Титульный лист с одним словом — это текстовый слой; страница-скан даёт
 * ноль символов или горсть мусора от подписи в колонтитуле. Между этими случаями разница в разы,
 * а не в процентах, поэтому число здесь не «настройка качества», а граница породы.
 */

/** Меньше этого числа значимых символов на странице — текстового слоя нет. */
export const PDF_TEXT_LAYER_MIN_CHARS = 16;

/** Значимые символы: пробелы и переводы строк не считаются — из них состоит пустая страница. */
function significantLength(text: string): number {
	return text.replace(/\s+/g, '').length;
}

/** Нужно ли распознавать страницу картинкой. */
export function pageNeedsOcr(text: string | undefined): boolean {
	return significantLength(text ?? '') < PDF_TEXT_LAYER_MIN_CHARS;
}

/** Пометка страницы в собранном тексте: читатель должен знать, что это распознавание, а не текст. */
export function pageHeading(pageNumber: number, viaOcr: boolean): string {
	return viaOcr ? `[Страница ${pageNumber} · распознано OCR]` : `[Страница ${pageNumber}]`;
}

/**
 * Строка о том, что часть документа прочитана распознаванием.
 *
 * Пусто, когда распознавать не пришлось. Нужна там, где человек видит итог: качество OCR ниже
 * текстового слоя, и об этом говорят заранее, а не когда модель ошиблась в цифре из таблицы.
 */
export function describeOcrPages(pageNumbers: readonly number[]): string {
	if (pageNumbers.length === 0) {
		return '';
	}
	const list = pageNumbers.length <= 5
		? pageNumbers.join(', ')
		: `${pageNumbers.slice(0, 5).join(', ')} и ещё ${pageNumbers.length - 5}`;
	return `Текстового слоя нет на страницах: ${list}. Они прочитаны распознаванием, точность ниже — цифры и имена сверяйте с оригиналом.`;
}
