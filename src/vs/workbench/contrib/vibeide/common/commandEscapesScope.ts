/**
 * Команда оболочки, которая уводит шаг за его границы записи.
 *
 * WHY: границы записи шага (`writeScope`) проверяются у инструментов правки — у них есть путь, и его
 * видно. У `run_command` пути нет: есть строка, и `cd ../other && rm -rf .` в ней выглядит как любая
 * другая строка. То есть шаг, которому разрешено писать в `docs/**`, мог переписать соседний `src/`,
 * просто попросив оболочку — граница была на двери, а окно стояло открытым.
 *
 * Разбор намеренно грубый и запрещающий. Оболочка — не язык с однозначным разбором: `eval`,
 * подстановка команд и переменные превращают строку во что угодно. Там, где команду нельзя прочитать
 * уверенно, ответ «нельзя» — а не «похоже, можно»: цена ошибки здесь несимметрична.
 *
 * Правило применяется ТОЛЬКО к шагу с объявленными границами. Обычный прогон агента ходит по проекту
 * свободно, и запрещать ему `cd` значило бы сломать работу ради дисциплины, о которой никто не просил.
 */

/** Почему команда не пропущена — человеческим языком, чтобы модель могла исправиться. */
export interface CommandEscape {
	readonly reason: string;
}

/** Смена рабочей папки: всё, что после неё, исполняется уже не там, где мы проверяли. */
const CHANGES_DIRECTORY = /(^|[;&|]\s*)(cd|pushd|popd)(\s|$)/;
/** Git с явным указанием чужого репозитория или дерева. */
const GIT_REDIRECT = /(^|\s)git(\s+--\w[\w-]*)*\s+(-C\s|--git-dir=|--work-tree=)/;
/** Те же перенаправления переменными окружения, в том числе перед командой. */
const GIT_ENV_REDIRECT = /(^|[;&|]\s*)(GIT_DIR|GIT_WORK_TREE|GIT_COMMON_DIR)\s*=/;
/** Конструкции, после которых строка перестаёт быть читаемой: подстановка, eval, исходник. */
const UNREADABLE = /\$\(|`|(^|\s)(eval|source|\.)\s/;

/**
 * Проверить команду шага с границами записи.
 *
 * `undefined` — команда читается и границ не обходит.
 */
export function commandEscapesScope(command: string): CommandEscape | undefined {
	const text = command.trim();
	if (!text) {
		return undefined;
	}
	if (CHANGES_DIRECTORY.test(text)) {
		return { reason: 'команда меняет рабочую папку (`cd`/`pushd`), а границы записи шага проверяются относительно папки проекта' };
	}
	if (GIT_REDIRECT.test(text) || GIT_ENV_REDIRECT.test(text)) {
		return { reason: 'команда направляет git в другой репозиторий или дерево (`-C`, `--git-dir`, `--work-tree`, `GIT_DIR`)' };
	}
	if (UNREADABLE.test(text)) {
		return { reason: 'команду нельзя прочитать уверенно: подстановка команды, `eval` или подключение чужого скрипта' };
	}
	return undefined;
}

/** Текст отказа для модели: что нарушено и что делать вместо. */
export function describeCommandEscape(command: string, escape: CommandEscape, allowedPaths: readonly string[] | undefined): string {
	const where = allowedPaths && allowedPaths.length > 0 ? allowedPaths.join(', ') : '(границы объявлены шагом)';
	return `Команда отклонена: ${escape.reason}. Шагу разрешено писать только в ${where}. Запусти команду из папки проекта и адресуй пути внутри границ, либо сообщи, что задача требует выхода за них: «${command.trim().slice(0, 120)}»`;
}
